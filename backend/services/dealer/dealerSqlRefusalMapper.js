/**
 * Inspect a PostgreSQL / PostgREST error object and return a deterministic HTTP Error
 * without leaking raw SQL statements, table structures, or private evidence.
 */
export function mapDealerSqlRefusal(error, fallbackOperation = 'dealership operation', defaultFallbackStatus = 503) {
  const text = String(error?.message || error?.details || error?.hint || '');
  for (const [code, statusCode] of Object.entries(DEALER_SQL_REFUSAL_STATUS_MAP)) {
    if (text.includes(code)) {
      const mapped = new Error(code);
      mapped.code = code;
      mapped.statusCode = statusCode;
      return mapped;
    }
  }
  if (/Append-only table/i.test(text)) {
    const immutable = new Error('IMMUTABLE_AUDIT_LEDGER_MUTATION_REFUSED');
    immutable.code = 'IMMUTABLE_AUDIT_LEDGER_MUTATION_REFUSED';
    immutable.statusCode = 403;
    return immutable;
  }
  if (error?.code === '23505') {
    const duplicate = new Error('DUPLICATE_DEALER_RECORD_CONFLICT');
    duplicate.code = 'DUPLICATE_DEALER_RECORD_CONFLICT';
    duplicate.statusCode = 409;
    return duplicate;
  }
  if (error?.code === '23503') {
    const fk = new Error('REFERENCED_DEALER_RECORD_NOT_FOUND');
    fk.code = 'REFERENCED_DEALER_RECORD_NOT_FOUND';
    fk.statusCode = 404;
    return fk;
  }
  if (error?.code === '23514') {
    const check = new Error('DEALER_DATA_CONSTRAINT_REFUSED');
    check.code = 'DEALER_DATA_CONSTRAINT_REFUSED';
    check.statusCode = 422;
    return check;
  }
  const unavailable = new Error(`${fallbackOperation} unavailable; no state change is confirmed`);
  unavailable.code = 'DEALER_SERVICE_UNAVAILABLE';
  unavailable.statusCode = defaultFallbackStatus;
  return unavailable;
}

/**
 * Format an HTTP error response in dealership routes, preserving explicit 4xx and 503 status codes
 * while ensuring 500 internal errors never leak SQL, stack traces, or private evidence.
 */
export function sendDealerRouteError(res, _next, error) {
  const status = Number(error?.statusCode);
  if (Number.isInteger(status) && status >= 400 && status <= 499) {
    res.set('Cache-Control', 'no-store').status(status).json({
      error: error.message,
      code: typeof error.code === 'string' ? error.code : undefined,
    });
    return;
  }
  if (status === 503) {
    res.set('Cache-Control', 'no-store').status(503).json({
      error: error.message || 'Dealership service temporarily unavailable; no state change is confirmed',
      code: typeof error.code === 'string' ? error.code : 'DEALER_SERVICE_UNAVAILABLE',
    });
    return;
  }
  res.set('Cache-Control', 'no-store').status(500).json({
    error: 'An unexpected internal server error occurred',
    code: 'INTERNAL_SERVER_ERROR',
  });
}
