/**
 * OC-LAUNCH-WEB-LR1-R15 — claim_due_communication_notifications() must not let old queue work starve
 * a human reply on WhatsApp or Telegram.
 *
 * Runs the REAL migration SQL against real PostgreSQL (PGlite 17). Each scenario is also run against
 * the migration's Down section — the pre-R15, strictly oldest-due definition — so the suite proves
 * the starvation it guards against actually happens without the fix.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const MIGRATION = '../../database/migrations/20261012100219_oc_launch_r15_admin_reply_claim_priority.sql';
const ORIGINAL = '../../database/migrations/20260624120000_communication_provider_runtime.sql';

const raw = readFileSync(new URL(MIGRATION, import.meta.url), 'utf8');
const UP = raw.slice(raw.indexOf('-- +migrate Up') + '-- +migrate Up'.length, raw.indexOf('-- +migrate Down'));
const DOWN = raw.slice(raw.indexOf('-- +migrate Down') + '-- +migrate Down'.length);

const SCHEMA = `
  CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
  CREATE TABLE notification_queue (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type text, notification_type text, channel text,
    status text NOT NULL DEFAULT 'queued',
    scheduled_at timestamptz, next_attempt_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz,
    attempt_count integer, locked_at timestamptz, locked_by text, dead_lettered_at timestamptz
  );`;

// Every database a test opens is closed once the file finishes; an open PGlite fails the process.
const open = [];
test.after(async () => { await Promise.all(open.map((db) => db.close())); });

async function database(definition = UP) {
  const db = await PGlite.create();
  open.push(db);
  await db.exec(SCHEMA);
  await db.exec(definition);
  return db;
}

// minutesAgo > 0 is due in the past; < 0 is scheduled in the future.
async function enqueue(db, { type = 'general', channel = 'in_app', minutesAgo, status = 'queued', ...extra }) {
  const cols = { type, notification_type: type, channel, status, ...extra };
  const names = Object.keys(cols);
  const { rows } = await db.query(
    `INSERT INTO notification_queue (${names.join(', ')}, created_at)
     VALUES (${names.map((_, i) => `$${i + 1}`).join(', ')}, now() - make_interval(mins => $${names.length + 1}))
     RETURNING id`,
    [...names.map((n) => cols[n]), minutesAgo],
  );
  return Number(rows[0].id);
}

async function backlog(db, count, { channel = 'in_app', oldestMinutesAgo = 60 * 24 * 38 } = {}) {
  for (let i = 0; i < count; i += 1) await enqueue(db, { channel, minutesAgo: oldestMinutesAgo - i });
}

async function claim(db, limit, worker = 'r15-test-worker', staleSeconds = 900) {
  const { rows } = await db.query('SELECT * FROM claim_due_communication_notifications($1, $2, $3)', [worker, limit, staleSeconds]);
  return rows;
}
const ids = (rows) => rows.map((r) => Number(r.id));

test('20+ older due in_app rows cannot block a newer due WhatsApp admin_reply (batch 1 claims the reply)', async () => {
  const db = await database();
  await backlog(db, 25);
  const reply = await enqueue(db, { type: 'admin_reply', channel: 'whatsapp', minutesAgo: 1 });
  assert.deepEqual(ids(await claim(db, 1)), [reply]);
});

test('NEGATIVE CONTROL — the pre-R15 definition starves that same WhatsApp reply', async () => {
  const db = await database(DOWN);
  await backlog(db, 25);
  const reply = await enqueue(db, { type: 'admin_reply', channel: 'whatsapp', minutesAgo: 1 });
  const first = await claim(db, 10);
  assert.equal(first.length, 10);
  assert.ok(!ids(first).includes(reply), 'the old order reaches the reply only after the backlog');
});

test('older null-channel legacy rows cannot block a newer due Telegram admin_reply', async () => {
  const db = await database();
  await backlog(db, 21, { channel: null });
  const reply = await enqueue(db, { type: 'admin_reply', channel: 'telegram', minutesAgo: 1 });
  assert.deepEqual(ids(await claim(db, 1)), [reply]);

  const control = await database(DOWN);
  await backlog(control, 21, { channel: null });
  const starved = await enqueue(control, { type: 'admin_reply', channel: 'telegram', minutesAgo: 1 });
  assert.notDeepEqual(ids(await claim(control, 1)), [starved]);
});

test('a batch claims every eligible reply first, then resumes the backlog oldest-due', async () => {
  const db = await database();
  const oldest = await enqueue(db, { minutesAgo: 600 });
  const next = await enqueue(db, { minutesAgo: 500 });
  await enqueue(db, { minutesAgo: 400 });
  const reply = await enqueue(db, { type: 'admin_reply', channel: 'whatsapp', minutesAgo: 1 });
  assert.deepEqual(ids(await claim(db, 3)), [reply, oldest, next]);
});

test('two eligible external admin replies keep due-time order relative to each other', async () => {
  const db = await database();
  await backlog(db, 20);
  const newer = await enqueue(db, { type: 'admin_reply', channel: 'whatsapp', minutesAgo: 2 });
  const older = await enqueue(db, { type: 'admin_reply', channel: 'telegram', minutesAgo: 9 });
  assert.deepEqual(ids(await claim(db, 1)), [older]);
  assert.deepEqual(ids(await claim(db, 1)), [newer]);
});

test('a WhatsApp/Telegram notification that is NOT admin_reply does not jump the queue', async () => {
  const db = await database();
  const oldest = await enqueue(db, { minutesAgo: 600 });
  await enqueue(db, { minutesAgo: 500 });
  await enqueue(db, { type: 'inquiry_received', channel: 'whatsapp', minutesAgo: 1 });
  await enqueue(db, { type: 'container_booking', channel: 'telegram', minutesAgo: 1 });
  assert.deepEqual(ids(await claim(db, 1)), [oldest]);
});

test('admin_reply on any other channel (email, in_app, push, null) does not jump the queue', async () => {
  const db = await database();
  const oldest = await enqueue(db, { minutesAgo: 600 });
  for (const channel of ['email', 'in_app', 'push', null]) {
    await enqueue(db, { type: 'admin_reply', channel, minutesAgo: 1 });
  }
  assert.deepEqual(ids(await claim(db, 1)), [oldest]);
});

test('with no qualifying reply, ordinary rows keep oldest-due order (next_attempt_at > scheduled_at > created_at)', async () => {
  const db = await database();
  const c = await enqueue(db, { minutesAgo: 30 });
  const a = await enqueue(db, { minutesAgo: 1, status: 'retry_scheduled', next_attempt_at: new Date(Date.now() - 90 * 60_000).toISOString() });
  const b = await enqueue(db, { channel: null, minutesAgo: 1, scheduled_at: new Date(Date.now() - 60 * 60_000).toISOString() });
  const d = await enqueue(db, { channel: 'email', minutesAgo: 10 });
  assert.deepEqual(ids(await claim(db, 10)), [a, b, c, d]);

  const control = await database(DOWN);
  const c2 = await enqueue(control, { minutesAgo: 30 });
  const a2 = await enqueue(control, { minutesAgo: 1, status: 'retry_scheduled', next_attempt_at: new Date(Date.now() - 90 * 60_000).toISOString() });
  const b2 = await enqueue(control, { channel: null, minutesAgo: 1, scheduled_at: new Date(Date.now() - 60 * 60_000).toISOString() });
  const d2 = await enqueue(control, { channel: 'email', minutesAgo: 10 });
  assert.deepEqual(ids(await claim(control, 10)), [a2, b2, c2, d2], 'identical to the pre-R15 order');
});

test('eligibility is unchanged: a not-yet-due, dead-lettered or freshly locked reply is never claimed', async () => {
  const db = await database();
  const oldest = await enqueue(db, { minutesAgo: 600 });
  await enqueue(db, { type: 'admin_reply', channel: 'whatsapp', minutesAgo: -30 });
  await enqueue(db, { type: 'admin_reply', channel: 'whatsapp', minutesAgo: 5, next_attempt_at: new Date(Date.now() + 10 * 60_000).toISOString(), status: 'retry_scheduled' });
  await enqueue(db, { type: 'admin_reply', channel: 'telegram', minutesAgo: 5, dead_lettered_at: new Date().toISOString() });
  await enqueue(db, { type: 'admin_reply', channel: 'whatsapp', minutesAgo: 5, status: 'processing', locked_at: new Date(Date.now() - 60_000).toISOString(), locked_by: 'other' });
  await enqueue(db, { type: 'admin_reply', channel: 'whatsapp', minutesAgo: 5, status: 'sent' });
  assert.deepEqual(ids(await claim(db, 10)), [oldest]);
});

test('stale-processing recovery is unchanged, and a stale reply is recovered ahead of the backlog', async () => {
  const db = await database();
  await backlog(db, 5);
  const stale = await enqueue(db, { type: 'admin_reply', channel: 'telegram', minutesAgo: 30, status: 'processing', locked_at: new Date(Date.now() - 20 * 60_000).toISOString(), locked_by: 'crashed', attempt_count: 1 });
  const [row] = await claim(db, 1, 'r15-recovery', 900);
  assert.equal(Number(row.id), stale);
  assert.equal(row.locked_by, 'r15-recovery');
  assert.equal(row.attempt_count, 2);
});

test('a claim marks the row processing, locks it to the worker and increments attempt_count once', async () => {
  const db = await database();
  const reply = await enqueue(db, { type: 'admin_reply', channel: 'whatsapp', minutesAgo: 1 });
  const [row] = await claim(db, 1, 'r15-worker');
  assert.equal(Number(row.id), reply);
  assert.equal(row.status, 'processing');
  assert.equal(row.locked_by, 'r15-worker');
  assert.ok(row.locked_at);
  assert.equal(row.attempt_count, 1);
  assert.deepEqual(await claim(db, 1), [], 'a freshly locked row is not claimed twice');
});

test('grants and security posture are unchanged: SECURITY DEFINER, search_path=public, service_role only', async () => {
  const db = await database();
  const { rows: [fn] } = await db.query(
    `SELECT p.prosecdef, p.proconfig,
            has_function_privilege('anon', p.oid, 'EXECUTE') AS anon,
            has_function_privilege('authenticated', p.oid, 'EXECUTE') AS authenticated,
            has_function_privilege('service_role', p.oid, 'EXECUTE') AS service_role
       FROM pg_proc p WHERE p.proname = 'claim_due_communication_notifications'`,
  );
  assert.equal(fn.prosecdef, true);
  assert.deepEqual(fn.proconfig, ['search_path=public']);
  assert.equal(fn.anon, false);
  assert.equal(fn.authenticated, false);
  assert.equal(fn.service_role, true);
});

// The same definition, compared as text: only the ORDER BY may differ from the original — so FOR UPDATE
// SKIP LOCKED (whose row-lock behaviour a single-connection PGlite cannot exercise), the stale-lock
// clause, dead-letter exclusion and the attempt increment are provably byte-for-byte the original.
const fnBody = (sql) => {
  const start = sql.indexOf('CREATE OR REPLACE FUNCTION');
  return sql.slice(start, sql.indexOf('$$;', start) + 3).replace('public.claim_due', 'claim_due').replace(/\s+/g, ' ').trim();
};
const ORIGINAL_FN = fnBody(readFileSync(new URL(ORIGINAL, import.meta.url), 'utf8'));

test('the new definition differs from the original ONLY in its ORDER BY', () => {
  const ORIGINAL_ORDER = 'ORDER BY COALESCE(next_attempt_at, scheduled_at::timestamptz, created_at::timestamptz, now()) ASC';
  const NEW_ORDER = "ORDER BY CASE WHEN notification_type = 'admin_reply' AND channel IN ('whatsapp', 'telegram') THEN 0 ELSE 1 END ASC, COALESCE(next_attempt_at, scheduled_at::timestamptz, created_at::timestamptz, now()) ASC";
  assert.ok(ORIGINAL_FN.includes(ORIGINAL_ORDER));
  assert.equal(fnBody(UP), ORIGINAL_FN.replace(ORIGINAL_ORDER, NEW_ORDER));
  assert.match(fnBody(UP), /FOR UPDATE SKIP LOCKED LIMIT GREATEST\(p_batch_limit, 1\)/);
});

test('the Down section restores the original definition exactly', () => {
  assert.equal(fnBody(DOWN), ORIGINAL_FN);
});
